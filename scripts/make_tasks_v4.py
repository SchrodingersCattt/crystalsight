def edge(x):
    return min(abs(x - np.floor(x)), abs(np.ceil(x) - x))


def ref_label(cr, ref):
    if ref:
        return ref
    return next(l for l, e, g in zip(cr.labels, cr.elems, cr.dgroup) if e != "H" and g in (".", "0"))


def gold_G1(cr, sp):
    a, inst = G.home_atom(cr, sp["H"])
    cs = [c for c in G.hb_contacts(cr, inst, ha_max=3.6, ang_min=0.0) if c["h"] == a]
    best = cs[0]
    second = next((c for c in cs[1:] if c["a_label"] != best["a_label"]), None)
    margin = (second["HA"] - best["HA"]) / best["HA"] if second else 9.99
    wrap = min(min(edge(x) for x in cr.c_frac[best["b"]]), min(edge(x) for x in cr.c_frac[a]))
    nacc = sum(e in ("N", "O") for e in cr.elems)
    donor = cr.c_label[best["d"]]
    q = (f"{CONV}\n\nReference: the home copy of hydrogen atom {sp['H']} (bonded to {donor}). Among all N and O atoms that "
         f"belong to OTHER molecules (any symmetry copy, any unit cell), which atom copy is closest to this H atom? Give its "
         f"copy-aware label.\nAnswer as JSON: {{\"acceptor\": \"SITE#k[i,j,k]\"}} (e.g. \"O2#3[0,1,0]\"; omit #1 and [0,0,0]).")
    chance = round(0.2 / nacc + 0.4 / len(cr.ops) + 0.4 / 27, 4)
    return dict(question=q, gold={"acceptor": best["a_label"]},
                options={"acceptor": f"copy-aware label SITE#k[i,j,k]; {nacc} N/O sites, {len(cr.ops)} operations"},
                numeric=dict(donor=donor, HA=round(best["HA"], 3), DA=round(best["DA"], 3), angle=round(best["angle"], 1),
                             second_nearest=(second["a_label"], round(second["HA"], 3)) if second else None,
                             wrap_margin=round(wrap, 3), candidates=sorted({c["a_label"] for c in cs[:6]})),
                margin=round(margin, 3), fragile=margin < FRAG or wrap < 0.02,
                method="Nearest N/O atom of another molecule to the home copy of the H over all operations and lattice shifts; "
                       "copy-aware label = generating operation + shift from its wrapped copy (verified identical to MatterVis label_sym).",
                chance=dict(exact=round(1 / (nacc * len(cr.ops) * 27), 5), weighted_expected=chance,
                            note="score = 0.2 site + 0.4 operation + 0.4 shift; shift chance over 27 shifts"),
                metric="partial: 0.2 x site label + 0.4 x operation index + 0.4 x lattice shift (score_v3); strict exact also reported")


def gold_G2(cr, sp):
    ref = ref_label(cr, sp["ref"])
    _, inst0 = G.home_atom(cr, ref)
    t = np.array(sp["t"])
    hs = []
    for p in PERT:
        E = G.hb_graph(cr, *p)
        hs.append(G.hb_hops(cr, inst0, (inst0[0], np.asarray(inst0[1]) + t), E, 12))
    tl = "[%d,%d,%d]" % tuple(t)
    g = "none" if hs[0] is None else str(hs[0])
    q = (f"{CONV}\n\nLet M0 be the molecule containing the home copy of {ref}, and M1 the copy of M0 translated by the lattice "
         f"vector {tl} (M1 contains {ref}{tl}). What is the minimum number of hydrogen bonds in a chain of molecules "
         f"M0 -> ... -> M1, where consecutive molecules in the chain are joined by at least one hydrogen bond (any "
         f"molecules and copies may be used)? If M1 cannot be reached from M0 through hydrogen bonds, answer \"none\".\n"
         f"Answer as JSON: {{\"hops\": \"<1-12 or none>\"}}.")
    return dict(question=q, gold={"hops": g}, options={"hops": [str(i) for i in range(1, 13)] + ["none"]},
                numeric=dict(ref=ref, t=list(t), hops_under_perturbation=[("none" if h is None else h) for h in hs]),
                margin=0.05 if len(set(map(str, hs))) == 1 else 0.0, fragile=len(set(map(str, hs))) != 1,
                method="Breadth-first search over molecule instances in the molecular H-bond graph (all operations and shifts); "
                       "answer unchanged with H...A 2.375/2.625 A and angle 114/126 deg.",
                chance=dict(exact=round(1 / 13, 4)), metric="exact match")


def gold_G3(cr, sp):
    a, inst = G.home_atom(cr, sp["H"])
    cs = [c for c in G.hb_contacts(cr, inst, 2.5, 120.0) if c["h"] == a]
    acc = cs[0]["a_label"]
    rs = []
    for p in PERT:
        r = G.hb_ring(cr, sp["H"], acc, *p, depth=4)
        rs.append(None if r is None else (r["ring_size"], r["n_molecules"]))
    r = G.hb_ring(cr, sp["H"], acc, 2.5, 120.0, depth=4)
    donor = cr.c_label[cs[0]["d"]]
    q = (f"{CONV}\n\nConsider the hydrogen bond {donor}-{sp['H']}...{acc} (home copies of {donor} and {sp['H']}; acceptor copy "
         f"{acc}). Find the smallest closed ring that contains this hydrogen bond and is made only of covalent bonds and "
         f"hydrogen bonds (a graph-set R ring). Count every atom in the ring, H atoms included, and count the distinct molecules "
         f"(distinct copies) the ring passes through.\nAnswer as JSON: {{\"ring_size\": <integer 4-48>, \"n_molecules\": <integer 1-12>}}.")
    alt_ok = len({(x[0], x[1]) for x in r["alternatives"]}) == 1
    return dict(question=q, gold={"ring_size": r["ring_size"], "n_molecules": r["n_molecules"]},
                options={"ring_size": "integer 4-48", "n_molecules": "integer 1-12"},
                numeric=dict(donor=donor, acceptor=acc, HA=round(cs[0]["HA"], 3), n_hbonds=r["n_hbonds"],
                             graph_set=f"R{r['n_acceptors']}^{r['n_hbonds']}({r['ring_size']})", path=r["path"],
                             under_perturbation=rs),
                margin=0.05 if len(set(rs)) == 1 and alt_ok else 0.0, fragile=not (len(set(rs)) == 1 and alt_ok),
                method="Shortest cycle through the given H...A edge in the atom graph (covalent + H-bond edges) over all molecule "
                       "copies within 4 H-bond hops; unique size/molecule count; unchanged under +-5 % H-bond criteria.",
                chance=dict(exact=round(1 / 45 / 12, 5), weighted_expected=round(0.5 / 45 + 0.5 / 12, 4)),
                metric="partial: 0.5 x ring_size + 0.5 x n_molecules (score_v3); strict exact also reported")


def gold_G4(cr, sp):
    ref = ref_label(cr, sp["ref"])
    _, inst0 = G.home_atom(cr, ref)
    R = sp["R"]
    if sp["mode"] == "centroid":
        d = np.array(G.centroid_shell(cr, inst0, R * 1.3))
        what = (f"have their centroid (unweighted mean of all atom positions, H included) within {R} A of the centroid of the "
                f"reference molecule")
    else:
        d = np.array([x[0] for x in G.neighbor_molecules(cr, inst0, cutoff=R * 1.3, rng=3)])
        what = f"have at least one atom within {R} A of any atom of the reference molecule (H atoms included)"
    n = int((d < R).sum())
    margin = float(np.min(np.abs(d - R) / R))
    q = (f"{CONV}\n\nReference molecule: the molecule containing the home copy of {ref}. How many OTHER molecules (every "
         f"symmetry copy and lattice translate counts separately; ions and water included) {what}?\n"
         f"Answer as JSON: {{\"count\": <integer 0-120>}}.")
    return dict(question=q, gold={"count": n}, options={"count": "integer 0-120"},
                numeric=dict(ref=ref, mode=sp["mode"], R=R, nearest_inside=round(float(d[d < R].max()), 3),
                             nearest_outside=round(float(d[d >= R].min()), 3)),
                margin=round(margin, 3), fragile=margin < FRAG,
                method=("Centroid" if sp["mode"] == "centroid" else "Minimum atom-atom") +
                       " distances from the reference molecule to every molecule copy over all operations and lattice shifts.",
                chance=dict(exact=round(1 / 121, 4)), metric="exact match")


def gold_G5(cr, sp):
    comp = G.disorder_components(cr)
    maj = sorted(g for g, o in comp.items() if o >= 0.5)
    mnr = sorted(g for g, o in comp.items() if o < 0.5)
    reps = {k: G.subset(cr, [g in (".", "0") or g in s for g in cr.dgroup]) for k, s in (("major", maj), ("minor", mnr))}
    refs, ds = {}, {}
    for k, rc in reps.items():
        if sp["ref"]:
            refs[k] = sp["ref"]
        else:  # whole-molecule disorder: first heavy atom of that component
            gs = maj if k == "major" else mnr
            refs[k] = next(l for l, e, g in zip(rc.labels, rc.elems, rc.dgroup) if e != "H" and g in gs)
        _, inst = G.home_atom(rc, refs[k])
        ds[k] = np.array([x[0] for x in G.neighbor_molecules(rc, inst, cutoff=6.0)])
    best = None
    for d in np.arange(3.0, 4.51, 0.05):
        m = min(float(np.min(np.abs(v - d) / d)) for v in ds.values())
        if m < FRAG:
            continue
        cnt = {k: int((v < d).sum()) for k, v in ds.items()}
        key = (cnt["major"] != cnt["minor"], m)
        if best is None or key > best[0]:
            best = (key, round(float(d), 2), cnt, m)
    if best is None:
        raise ValueError("no robust cutoff")
    _, d, cnt, m = best
    occ = {g: round(o, 3) for g, o in comp.items()}
    refq = (f"the molecule containing the home copy of {refs['major']}" if refs["major"] == refs["minor"] else
            f"in MAJOR the molecule containing the home copy of {refs['major']}, in MINOR the molecule containing the home copy of {refs['minor']}")
    q = (f"{CONV}\n\nThis structure is disordered: some sites belong to disorder groups (_atom_site_disorder_group / PART) with "
         f"partial occupancy. Build two ordered models. MAJOR keeps every site without a disorder group plus the disorder "
         f"group(s) with the higher occupancy; MINOR keeps every site without a disorder group plus the disorder group(s) with "
         f"the lower occupancy. In each model, count the OTHER molecules (all symmetry copies and lattice translates; ions and "
         f"solvent included) that have at least one atom within {d} A of any atom of the reference molecule ({refq}).\n"
         f"Answer as JSON: {{\"major\": <integer 0-40>, \"minor\": <integer 0-40>}}.")
    return dict(question=q, gold={"major": cnt["major"], "minor": cnt["minor"]},
                options={"major": "integer 0-40", "minor": "integer 0-40"},
                numeric=dict(cutoff=d, groups_occupancy=occ, major_groups=maj, minor_groups=mnr, refs=refs,
                             major_dists=[round(float(x), 2) for x in ds["major"][:24]],
                             minor_dists=[round(float(x), 2) for x in ds["minor"][:24]]),
                margin=round(m, 3), fragile=m < FRAG,
                method="Ordered replicas from the CIF disorder groups (higher vs lower mean occupancy), re-expanded; minimum "
                       "atom-atom distance to every other molecule copy; cutoff chosen with >= 5 % gap in both replicas.",
                chance=dict(exact=round(1 / 41 ** 2, 5), weighted_expected=round(1 / 41, 4)),
                metric="partial: 0.5 x major + 0.5 x minor (score_v3); strict exact also reported")


