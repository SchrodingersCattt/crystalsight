"""Channel 3: interactive ASCII. A text-only model drives a MatterVis
TerminalSession (same engine as ``mat-vis tui --session-format jsonl``).

Leakage control: the model sees ONLY the rendered frame lines plus the camera
state. The observation's title, scope (formula/atom counts) and warnings
(which name molecule IDs) are withheld. Perception-only actions are allowed;
select/focus (which open the chemistry inspector) are refused, following the
MatterVis ``inspect-structure-tui`` skill.
"""

from __future__ import annotations

import hashlib
import json
import os
import pickle
import subprocess
import sys
import threading
from pathlib import Path

from ..models import extract_json
from ..paths import CACHE, ROOT, SUBPROCESS_ENV
from .base import SYSTEM, Channel, answer_instructions, task_structures, unwrap

ALLOWED = ("observe", "reset", "orbit", "align", "pan", "zoom", "fit", "set_display", "distance", "set_component")
EXTRA_DISPLAY = ("show_hbonds", "hbond_max_ha", "hbond_min_angle")  # handled by tui_extras, not by mat-vis
WIDTH, HEIGHT = 100, 36

GUIDE = f"""You are looking at the structure through a {WIDTH}x{HEIGHT} ASCII terminal renderer
(MatterVis TUI, ASCII-7 charset, orthographic). Scene: {{scene}}. You cannot see coordinates.
Each turn reply with exactly ONE JSON object, either an action or the final answer:
  {{"action": "orbit", "arguments": {{"yaw_deg": 30, "pitch_deg": 15}}}}
  {{"action": "align", "arguments": {{"axis": "c"}}}}            axes: a b c a* b* c*
  {{"action": "zoom", "arguments": {{"factor": 1.5}}}}
  {{"action": "pan", "arguments": {{"dx": 0.1, "dy": 0.0}}}}
  {{"action": "fit", "arguments": {{"target": "all"}}}}
  {{"action": "set_display", "arguments": {{"display_level": "atom", "label_mode": "label_sym", "show_bonds": true, "show_cell": true, "show_axes": true}}}}
     display_level: auto | atom | molecule   (molecule = one marker per molecule)
     label_mode: auto | label | label_sym | element | molecule | dot   ("none" is accepted as dot)
       label     = CIF site label, e.g. O1 (all symmetry copies of a site share it)
       label_sym = copy-aware label: O1#k[i,j,k] is site O1 generated by symmetry operation k of the
                   CIF symmetry list (#k omitted for operation 1 = x,y,z), shifted by the lattice
                   vector [i,j,k] from its copy in the home cell ([i,j,k] omitted when 0,0,0)
       element   = element symbol; molecule = label + molecule index; dot = marker only
       auto      = label, element or dot depending on how crowded the view is
     show_axes: the bottom row shows where a, b, c point on screen (E=right, N=up, NE, ...; out = toward
                you, in = away) and a scale bar in Angstrom
     show_hbonds (ad hoc overlay): true draws ':' dotted lines from H to acceptor for hydrogen bonds whose two
                atoms are on screen and lists them under the frame as D-H...A with copy-aware labels, H...A (A) and
                angle; criteria: "hbond_max_ha": 2.5, "hbond_min_angle": 120 (set them to what the question uses)
  {{"action": "distance", "arguments": {{"a": "H2", "b": "O3#3[0,1,0]"}}}}   distance in A between two scene atoms
                given by copy-aware labels (as printed in label_sym mode)
  {{"action": "set_component", "arguments": {{"component": "major"}}}}   disordered structures only: reload the scene
                with the sites without a disorder group plus only the major (higher-occupancy) or minor disorder
                group(s); "all" restores the full scene. Labels and symmetry numbering are unchanged.
  {{"action": "reset", "arguments": {{}}}}
  {{"answer": ...}}
Allowed actions: {", ".join(ALLOWED)}. You have a budget of {{budget}} actions; after that you must answer."""

DEFAULT_SCENE = "one unit cell plus the boundary copies on its faces"


def scene_text(opts: dict) -> str:
    """Describe the load-time scene (mat-vis repeat / grow_radius transforms) to the model."""
    if opts.get("repeat"):
        na, nb, nc = opts["repeat"] if isinstance(opts["repeat"], (list, tuple)) else (opts["repeat"],) * 3
        return f"a {na}x{nb}x{nc} supercell"
    if opts.get("grow_radius"):
        return (f"one unit cell plus every periodic image atom within {float(opts['grow_radius']):g} A of it "
                "(so molecules across cell faces are partly shown)")
    return DEFAULT_SCENE


# Task-level TUI options (tasks_v3 "tui" field). Load-time keys go to mat-vis load_for_tui; view keys to
# TerminalSession. Tasks without the field keep the original behaviour (unit cell, label_mode auto).
LOAD_KEYS = ("repeat", "grow_radius")
VIEW_KEYS = ("label_mode", "display_level", "show_axes", "show_bonds", "show_cell")


def tui_options(task: dict) -> tuple[dict, dict]:
    opts = dict(task.get("tui") or {})
    return {k: opts[k] for k in LOAD_KEYS if opts.get(k)}, {k: opts[k] for k in VIEW_KEYS if k in opts}


def extra_options(task: dict) -> dict:
    opts = dict(task.get("tui") or {})
    return {"show_hbonds": bool(opts.get("show_hbonds", False)), "hbond_max_ha": float(opts.get("hbond_max_ha", 2.5)),
            "hbond_min_angle": float(opts.get("hbond_min_angle", 120.0))}


def _frame(obs: dict) -> str:
    cam = obs.get("camera", {})
    disp = obs.get("display", {})
    head = (f"[camera az={cam.get('azimuth', 0):.0f} el={cam.get('elevation', 0):.0f} roll={cam.get('roll', 0):.0f} "
            f"zoom={cam.get('zoom', 1):.2f}] [display level={disp.get('display_level')} labels={disp.get('label_mode')} "
            f"bonds={disp.get('show_bonds')} cell={disp.get('show_cell')} axes={disp.get('show_axes', False)}]")
    return head + "\n" + obs["frame"]["text"]


_crystals: dict[str, object] = {}
_clock = threading.Lock()
_slocks: dict[str, threading.Lock] = {}

# Building the TUI CrystalIR runs full MolCrysKit perception. For a few heavily
# disordered structures (e.g. mck_anhydrousCaffeine2) it does not finish in >1 h,
# which previously stalled the whole run. It now runs in a child process with a
# hard timeout; a failure is cached as a ``.failed`` marker and the task is
# recorded as an infrastructure error (excluded from scoring) instead of hanging.
TUI_LOAD_TIMEOUT_S = int(os.environ.get("CRYSTALSIGHT_TUI_LOAD_TIMEOUT", "600"))
_LOADER = (
    "import json, pickle, sys\n"
    "from mat_viewer.tui.loader_adapter import load_for_tui\n"
    "kw = json.loads(sys.argv[3]) if len(sys.argv) > 3 else {}\n"
    "c = load_for_tui(sys.argv[1], display_mode='auto', **kw)\n"
    "open(sys.argv[2], 'wb').write(pickle.dumps(c))\n"
)


class TuiLoadError(RuntimeError):
    pass


def _kill_tree(proc: subprocess.Popen) -> None:
    """Kill the loader and every descendant.  On Windows a venv python.exe is a launcher that starts the base
    interpreter as a child, so killing only proc.pid would leave the real worker running (and holding the pipes)."""
    kids = []
    try:
        import psutil
        kids = psutil.Process(proc.pid).children(recursive=True)
    except Exception:  # noqa: BLE001 - psutil missing or process already gone
        if os.name == "nt":
            kids = _win_descendants(proc.pid)
    if os.name == "nt":
        subprocess.run(["taskkill", "/PID", str(proc.pid), "/T", "/F"], capture_output=True, check=False)
    else:
        proc.kill()
    for k in kids:  # descendants that taskkill /T missed (e.g. re-parented after the launcher died)
        try:
            if isinstance(k, int):
                subprocess.run(["taskkill", "/PID", str(k), "/T", "/F"], capture_output=True, check=False)
            else:
                k.kill()
        except Exception:  # noqa: BLE001, S110
            pass


def _win_descendants(pid: int) -> list[int]:
    """Descendant PIDs of pid on Windows without psutil (one CIM query, then walk the parent map)."""
    try:
        out = subprocess.run(["powershell", "-NoProfile", "-Command",
                              "Get-CimInstance Win32_Process | ForEach-Object { \"$($_.ProcessId) $($_.ParentProcessId)\" }"],
                             capture_output=True, text=True, timeout=60, check=False).stdout
    except Exception:  # noqa: BLE001
        return []
    children: dict[int, list[int]] = {}
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 2 and all(x.isdigit() for x in parts):
            children.setdefault(int(parts[1]), []).append(int(parts[0]))
    res, stack = [], [pid]
    while stack:
        for c in children.get(stack.pop(), []):
            if c not in res:
                res.append(c); stack.append(c)
    return res


def _build_pickle(path: Path, pkl: Path, failed: Path, load_opts: dict | None = None) -> None:
    pkl.parent.mkdir(parents=True, exist_ok=True)
    tmp = pkl.with_suffix(".tmp")
    tmp.unlink(missing_ok=True)
    argv = [sys.executable, "-c", _LOADER, str(path), str(tmp)] + ([json.dumps(load_opts)] if load_opts else [])
    proc = subprocess.Popen(argv, stdout=subprocess.PIPE,
                            stderr=subprocess.PIPE, text=True, encoding="utf-8", errors="replace", env=SUBPROCESS_ENV)
    try:
        _, err = proc.communicate(timeout=TUI_LOAD_TIMEOUT_S)
    except subprocess.TimeoutExpired:
        _kill_tree(proc)
        try:
            proc.communicate(timeout=30)
        except subprocess.TimeoutExpired:
            pass
        failed.write_text(f"TUI load timeout after {TUI_LOAD_TIMEOUT_S}s", encoding="utf-8")
        raise TuiLoadError(failed.read_text(encoding="utf-8"))
    if proc.returncode != 0 or not tmp.exists():
        failed.write_text(f"TUI load failed (rc={proc.returncode}): {(err or '')[-400:]}", encoding="utf-8")
        raise TuiLoadError(failed.read_text(encoding="utf-8"))
    tmp.replace(pkl)


def load_crystal(structure_id: str, path: Path, load_opts: dict | None = None):
    """Load the MatterVis terminal CrystalIR once per (structure, load options) (memory + pickle cache)."""
    load_opts = dict(load_opts or {})
    opt_tag = ""
    if load_opts:  # supercell / neighbour-shell scenes are cached separately from the plain unit cell
        opt_tag = "_" + hashlib.sha256(json.dumps(load_opts, sort_keys=True).encode()).hexdigest()[:8]
    key = structure_id + opt_tag
    with _clock:
        lock = _slocks.setdefault(key, threading.Lock())
    with lock:
        if key in _crystals:
            return _crystals[key]
        digest = hashlib.sha256(path.read_bytes()).hexdigest()[:16]
        pkl = CACHE / "tui" / f"{structure_id}_{digest}{opt_tag}.pkl"
        failed = pkl.with_suffix(".failed")
        if failed.exists():
            raise TuiLoadError(failed.read_text(encoding="utf-8"))
        crystal = None
        if pkl.exists():
            try:
                crystal = pickle.loads(pkl.read_bytes())
            except Exception:  # noqa: BLE001 - stale/incompatible cache
                crystal = None
        if crystal is None:
            _build_pickle(path, pkl, failed, load_opts)
            crystal = pickle.loads(pkl.read_bytes())
        _crystals[key] = crystal
        return crystal


PAIR_GUIDE = """
Two structures (A and B) are loaded in separate viewers; actions apply to the active one.
  {"action": "switch", "arguments": {"structure": "B"}}   makes B active and shows its current view (costs one action)."""


class TuiChannel(Channel):
    name = "tui"
    max_steps = 8

    def __init__(self, budget: int = 8):
        self.budget = budget

    def run(self, task, model):
        from mat_viewer.tui import TerminalAction, TerminalSession

        rec = {"channel": self.name, "steps": 0, "frames": [], "actions": []}
        structs = task_structures(task)
        load_opts, view_opts = tui_options(task)
        rec["tui_options"] = {**load_opts, **view_opts}
        from .tui_extras import SceneAnalyzer, component_cif, hbond_overlay
        sessions, extras = {}, {}
        for st in structs:
            crystal = load_crystal(st["structure_id"], Path(ROOT / st["path"]), load_opts)
            sessions[st["label"]] = TerminalSession(crystal, width=WIDTH, height=HEIGHT, charset="ascii7", **view_opts)
            extras[st["label"]] = dict(extra_options(task), crystal=crystal, analyzer=None, st=st, component="all")

        def render(lab, obs):
            """mat-vis frame plus the ad hoc H-bond overlay (tui_extras) when switched on."""
            ex = extras[lab]
            if ex["show_hbonds"] and "frame" in obs:
                if ex["analyzer"] is None:
                    ex["analyzer"] = SceneAnalyzer(ex["crystal"])
                obs = dict(obs, frame=dict(obs["frame"], text=hbond_overlay(sessions[lab], ex["analyzer"], obs["frame"]["text"],
                                                                         ex["hbond_max_ha"], ex["hbond_min_angle"])))
            return _frame(obs)
        labels = list(sessions)
        active = labels[0]
        pair = len(labels) > 1
        budget = self.budget * (2 if pair else 1)
        allowed = ALLOWED + (("switch",) if pair else ())

        def tag(label):
            return f"[structure {label}] " if pair else ""

        initial = []
        for lab in labels:
            fr = tag(lab) + render(lab, sessions[lab].observe().as_dict())
            rec["frames"].append(fr)
            initial.append(fr)
        guide = GUIDE.replace("{budget}", str(budget)).replace("{scene}", scene_text(load_opts)) + (PAIR_GUIDE if pair else "")
        msgs = [{"role": "system", "content": SYSTEM},
                {"role": "user", "content": f"Question: {task['question']}\n{answer_instructions(task)}\n\n{guide}\n\n"
                                            f"Initial view{'s' if pair else ''} (active: {active or 'the structure'}):\n" + "\n\n".join(initial)}]
        self.log_turn(rec, "user", f"Question: {task['question']}\n<initial frame(s)>")
        invalid = 0
        for step in range(budget + 1):
            r = model.complete(msgs, context={"task": task, "channel": self.name, "step": step})
            self.usage_add(rec, r.usage, r.latency_ms)
            if r.error:
                rec["error"] = r.error
                rec["answer"] = None
                return rec
            self.log_turn(rec, "assistant", r.text[-2000:])
            rec["steps"] = step + 1
            raw = extract_json(r.text) or {}
            parsed = unwrap(raw) or raw
            if "answer" in parsed:
                return self.final(rec, r.text)
            if step >= budget:
                break
            name = parsed.get("action")
            args = parsed.get("arguments") or {}
            msgs.append({"role": "assistant", "content": r.text})
            left = budget - step - 1
            if name not in allowed:
                invalid += 1
                feedback = f"Invalid action {name!r}. Allowed: {', '.join(allowed)}. Reply with one JSON object."
                rec["actions"].append({"action": name, "ok": False})
                if invalid >= 2:
                    msgs.append({"role": "user", "content": feedback + " Two invalid actions in a row: answer now."})
                    self.log_turn(rec, "user", "<two invalid actions; forced answer>")
                    r = model.complete(msgs, context={"task": task, "channel": self.name, "step": budget})
                    self.usage_add(rec, r.usage, r.latency_ms)
                    self.log_turn(rec, "assistant", r.text[-2000:])
                    return self.final(rec, r.text)
            elif name == "switch":
                want = str(args.get("structure", "")).strip().upper()
                if want in sessions:
                    active, invalid = want, 0
                    frame = tag(active) + render(active, sessions[active].observe().as_dict())
                    rec["frames"].append(frame)
                    rec["actions"].append({"action": name, "arguments": args, "ok": True})
                    feedback = f"Now viewing structure {active} ({left} actions left):\n{frame}"
                else:
                    invalid += 1
                    rec["actions"].append({"action": name, "arguments": args, "ok": False})
                    feedback = f"Unknown structure {want!r}; use A or B."
            elif name == "distance":
                ex = extras[active]
                if ex["analyzer"] is None:
                    ex["analyzer"] = SceneAnalyzer(ex["crystal"])
                res = ex["analyzer"].distance(args.get("a", ""), args.get("b", ""))
                ok = res.startswith("distance ") and "not in the scene" not in res
                invalid = 0 if ok else invalid + 1
                rec["actions"].append({"action": name, "arguments": args, "ok": ok, "result": res})
                feedback = f"{res} ({left} actions left)"
            else:
                try:
                    if name == "set_component":
                        ex = extras[active]
                        comp = str(args.get("component", "all")).lower()
                        if comp not in ("all", "major", "minor"):
                            raise ValueError("component must be all, major or minor")
                        src = Path(ROOT / ex["st"]["path"])
                        path = src if comp == "all" else component_cif(src, comp)
                        sid = ex["st"]["structure_id"] + ("" if comp == "all" else f"__{comp}")
                        ex["crystal"] = load_crystal(sid, path, load_opts)
                        ex["analyzer"], ex["component"] = None, comp
                        sessions[active] = TerminalSession(ex["crystal"], width=WIDTH, height=HEIGHT, charset="ascii7", **view_opts)
                        obs = sessions[active].observe().as_dict()
                    else:
                        if name == "set_display":
                            args = dict(args)
                            for k in EXTRA_DISPLAY:
                                if k in args:
                                    v = args.pop(k)
                                    extras[active][k] = bool(v) if k == "show_hbonds" else float(v)
                        obs = sessions[active].execute(TerminalAction(name, dict(args))).as_dict()
                    if "frame" not in obs:
                        raise ValueError(obs.get("error") or "action returned no frame")
                    invalid = 0
                    frame = tag(active) + render(active, obs)
                    rec["frames"].append(frame)
                    rec["actions"].append({"action": name, "arguments": args, "ok": True, "structure": active})
                    feedback = f"View after {name} ({left} actions left):\n{frame}"
                except Exception as exc:  # noqa: BLE001 - structured error back to model
                    invalid += 1
                    rec["actions"].append({"action": name, "arguments": args, "ok": False, "error": str(exc)[:200]})
                    feedback = f"Action error: {str(exc)[:200]}. Reply with one JSON object."
            msgs.append({"role": "user", "content": feedback})
            self.log_turn(rec, "user", feedback.split("\n", 1)[0])
        msgs.append({"role": "user", "content": "Action budget exhausted. Reply now with {\"answer\": ...} only."})
        r = model.complete(msgs, context={"task": task, "channel": self.name, "step": budget + 1})
        self.usage_add(rec, r.usage, r.latency_ms)
        self.log_turn(rec, "assistant", r.text[-2000:])
        return self.final(rec, r.text)
