def main():
    OUT.mkdir(exist_ok=True)
    verdicts = {}
    vf = OUT / "tui_verdicts_v4.json"
    if vf.exists():
        verdicts = json.loads(vf.read_text(encoding="utf-8"))
    tasks, cnt = [], {}
    for sp in SPECS:
        cnt[sp["fam"]] = cnt.get(sp["fam"], 0) + 1
        t = build(sp, cnt[sp["fam"]])
        if t["id"] in verdicts:
            t["tui_feasibility"] = verdicts[t["id"]]
        tasks.append(t)
        print(t["id"], json.dumps(t["gold"]), "margin", t["margin"], "FRAGILE" if t["fragile"] else "", flush=True)
