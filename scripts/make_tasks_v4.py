def schema_for(fam, g, res):
    if fam == "G1":
        return {"acceptor": {"type": "label", "hint": "copy-aware label SITE#k[i,j,k]", "candidates": res["numeric"]["candidates"]}}
    if fam == "G2":
        return {"hops": {"type": "choice", "options": res["options"]["hops"]}}
    return {k: {"type": "int"} for k in g}


def build(sp, n):
    cr = G.load(ROOT / path_of(sp["sid"]))
    res = GOLD[sp["fam"]](cr, sp)
    tid = f"v4_{sp['fam']}_{n:02d}_{sp['sid']}"
    tui = {"label_mode": "label_sym", "display_level": "atom", "show_axes": True, **TUI[sp["fam"]]}
    if sp.get("grow"):  # centroid shells: the scene must hold every molecule whose centroid is inside R
        tui["grow_radius"] = sp["grow"]
    disorder = any(g not in (".", "0") for g in cr.dgroup) or bool((cr.occ < 0.99).any())
    return dict(id=tid, family=sp["fam"], structure_id=sp["sid"], structure_name=NAMES[sp["sid"]], path=path_of(sp["sid"]),
                question=res["question"], options=res["options"], gold=res["gold"],
                score_weights=WEIGHTS[sp["fam"]], gold_method=res["method"], numeric=res["numeric"], margin=res["margin"],
                fragile=res["fragile"], metric=res["metric"], chance=res["chance"], why_hard_from_cif_text=WHY[sp["fam"]],
                tui_path=TOOL[sp["fam"]][0], mck_tool_path=TOOL[sp["fam"]][1], adhoc_tool_path=TOOL_ADHOC[sp["fam"]],
                space_group_ops=len(cr.ops),
                molecules_in_cell=len(cr.mols), z_prime=round(len(cr.mols) / len(cr.ops), 2),
                h_atoms_present="H" in cr.elems, disorder_present=disorder,
                licensed_source="CSD-derived; local only (gitignored), anonymised id" if sp["sid"].startswith("ccdc_") else None,
                benchmark="v4", qtype=QTYPE[sp["fam"]], answer_type="object", schema=schema_for(sp["fam"], res["gold"], res),
                tui=tui)


